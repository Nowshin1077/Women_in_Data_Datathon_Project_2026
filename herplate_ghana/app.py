# -----------------------------------------------------------------------------
# 5. DIAGNOSTIC VISUALIZATION (HERO GRAPH)
# -----------------------------------------------------------------------------
st.subheader("📊 The Diagnostic Overview: Supply Trend vs. Women's Plate Consumption")

def extract_val(df, keyword, fallback):
    try:
        match = df[df['Food_Group'].astype(str).str.contains(keyword, case=False, na=False)]
        if not match.empty and target_col in match.columns:
            return float(match[target_col].values[0])
    except Exception:
        pass
    return fallback

summary_data = [
    {"Food Group": "🥛 Dairy Products", "Consumption_Pct": extract_val(mddw_df, "dairy", 15.4) + (asf_subsidy * 0.2), "Supply_Trend_Pct": -24.4},
    {"Food Group": "🫘 Pulses (Beans & Peas)", "Consumption_Pct": extract_val(mddw_df, "pulse", 23.5), "Supply_Trend_Pct": -39.4},
    {"Food Group": "🥚 Eggs", "Consumption_Pct": extract_val(mddw_df, "egg", 27.6) + (asf_subsidy * 0.3), "Supply_Trend_Pct": 3.9},
    {"Food Group": "🥬 Vegetables", "Consumption_Pct": extract_val(mddw_df, "veg", 51.5), "Supply_Trend_Pct": -40.7}
]
df_hero = pd.DataFrame(summary_data)

chart_mode = st.radio(
    "Select Diagnostic View:",
    ["Side-by-Side Comparison (2022 Baseline)", "13-Year National Supply Trajectories (2010 - 2023)"],
    horizontal=True
)

if chart_mode == "Side-by-Side Comparison (2022 Baseline)":
    fig = go.Figure()
    fig.add_trace(go.Bar(
        x=df_hero["Food Group"],
        y=df_hero["Consumption_Pct"],
        name="Women's Consumption Rate (%)",
        marker_color="#3B82F6",
        text=df_hero["Consumption_Pct"].round(1).astype(str) + "%",
        textposition="auto"
    ))
    fig.add_trace(go.Bar(
        x=df_hero["Food Group"],
        y=df_hero["Supply_Trend_Pct"],
        name="10-Yr National Supply Trend (%)",
        marker_color=["#EF4444" if v < 0 else "#10B981" for v in df_hero["Supply_Trend_Pct"]],
        text=df_hero["Supply_Trend_Pct"].astype(str) + "%",
        textposition="auto"
    ))
    fig.update_layout(
        title=f"National Food Supply Trends vs. Women's Plate Consumption ({location_filter})",
        barmode="group",
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        height=450,
        legend=dict(x=0.01, y=0.98, orientation="h")
    )
    st.plotly_chart(fig, use_container_width=True)
else:
    fig_ts = go.Figure()
    fig_ts.add_trace(go.Scatter(x=fbs_df["Year"], y=fbs_df["Dairy_Supply"], mode="lines+markers", name="🥛 Dairy Supply (g/day)", line=dict(color="#EF4444", width=3)))
    fig_ts.add_trace(go.Scatter(x=fbs_df["Year"], y=fbs_df["Pulses_Supply"], mode="lines+markers", name="🫘 Pulses Supply (g/day)", line=dict(color="#F59E0B", width=3)))
    fig_ts.add_trace(go.Scatter(x=fbs_df["Year"], y=fbs_df["Eggs_Supply"], mode="lines+markers", name="🥚 Eggs Supply (g/day)", line=dict(color="#3B82F6", width=3)))
    fig_ts.add_trace(go.Scatter(x=fbs_df["Year"], y=fbs_df["Vegetables_Supply"], mode="lines+markers", name="🥬 Vegetables Supply (g/day)", line=dict(color="#10B981", width=3)))
    fig_ts.update_layout(
        title="13-Year Per-Capita Food Availability Trajectories in Ghana (2010 - 2023)",
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        height=450,
        legend=dict(x=0.01, y=0.98, orientation="h")
    )
    st.plotly_chart(fig_ts, use_container_width=True)

