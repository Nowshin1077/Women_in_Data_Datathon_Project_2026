if asf_subsidy > 0:
    st.sidebar.success(f"💡 Simulating a {asf_subsidy}% subsidy on Animal-Source Foods.")

# -----------------------------------------------------------------------------
# 4. DASHBOARD HEADER & TOP KPIs
# -----------------------------------------------------------------------------
st.title("🇬🇭 HerPlate Ghana: Food System Bottleneck Diagnostic")
st.markdown("**Core Diagnostic Question:** *Where is the pathway from Ghana's food system to women's plates breaking?*")

latest_afford_pct = float(cahd_df['Unable_To_Afford_Pct'].iloc[-1]) if 'Unable_To_Afford_Pct' in cahd_df.columns else 64.7
latest_asf_share = float(cahd_df['ASF_Cost_Share_Pct'].iloc[-1]) if 'ASF_Cost_Share_Pct' in cahd_df.columns else 41.1

k1, k2, k3, k4 = st.columns(4)
k1.metric("Unable to Afford Healthy Diet", f"{latest_afford_pct:.1f}%", "UN FAOSTAT Baseline (2022)")
k2.metric("Animal Food Basket Share", f"{latest_asf_share:.1f}%", "Largest Diet Cost Contributor")
